use super::{SUBFRAME_CODE_BITS, SUBFRAME_SAMPLES, VselpSubframe};

pub(super) const BASIS_COUNT: usize = SUBFRAME_CODE_BITS as usize;
const CODEBOOK_COUNT: usize = 2;
/// Unweighted IS-54-B §2.1.3.3.2.6.4 vector sums before gain reconstruction.
#[derive(Debug, Clone, PartialEq)]
pub struct CodebookExcitation {
    pub codebook_one: [f64; SUBFRAME_SAMPLES],
    pub codebook_two: [f64; SUBFRAME_SAMPLES],
}
pub(super) fn decode(subframe: &VselpSubframe) -> CodebookExcitation {
    CodebookExcitation {
        codebook_one: vector(&BASIS_VECTORS[0], subframe.code1()),
        codebook_two: vector(&BASIS_VECTORS[1], subframe.code2()),
    }
}
pub(super) fn basis(book: usize) -> &'static [[f64; SUBFRAME_SAMPLES]; BASIS_COUNT] {
    &BASIS_VECTORS[book]
}
// IS-54-B §§2.1.3.3.2.6.4 and 2.1.3.3.2.6.4.4: set bits add vectors, bit zero selects basis one.
pub(super) fn vector(
    basis: &[[f64; SUBFRAME_SAMPLES]; BASIS_COUNT],
    code: u8,
) -> [f64; SUBFRAME_SAMPLES] {
    std::array::from_fn(|sample| {
        basis
            .iter()
            .enumerate()
            .map(|(bit, values)| {
                if code & (1 << bit) != 0 {
                    values[sample]
                } else {
                    -values[sample]
                }
            })
            .sum()
    })
}
