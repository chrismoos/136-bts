    const WORDS: u8 = 1 << SUBFRAME_CODE_BITS;
    #[test]
    fn all_560_basis_samples_are_finite_and_each_vector_has_nonzero_energy() {
        assert_eq!(BASIS_VECTORS.iter().flatten().flatten().count(), 560);
        for basis in BASIS_VECTORS.iter().flatten() {
            assert!(basis.iter().all(|value| value.is_finite()));
            assert!(basis.iter().map(|value| value * value).sum::<f64>() > 0.0);
        }
    }
    #[test]
    fn every_complementary_codeword_produces_the_negative_excitation() {
        for code in 0..WORDS {
            let complement = code ^ (WORDS - 1);
            let first = decode(&VselpSubframe::try_new(0, code, code, 0).unwrap());
            let second = decode(&VselpSubframe::try_new(0, complement, complement, 0).unwrap());
            for (positive, negative) in first
                .codebook_one
                .iter()
                .chain(&first.codebook_two)
                .zip(second.codebook_one.iter().chain(&second.codebook_two))
            {
                assert!((positive + negative).abs() < 1e-12);
            }
        }
    }
    #[test]
    fn each_codeword_bit_controls_the_corresponding_basis_vector() {
        let base = decode(&VselpSubframe::try_new(0, 0, 0, 0).unwrap());
        for (bit, (basis_one, basis_two)) in
            BASIS_VECTORS[0].iter().zip(&BASIS_VECTORS[1]).enumerate()
        {
            let one = decode(&VselpSubframe::try_new(0, 1 << bit, 1 << bit, 0).unwrap());
            for (sample, (basis_one, basis_two)) in basis_one.iter().zip(basis_two).enumerate() {
                assert!(
                    (one.codebook_one[sample] - base.codebook_one[sample] - 2.0 * *basis_one).abs()
                        < 1e-12
                );
                assert!(
                    (one.codebook_two[sample] - base.codebook_two[sample] - 2.0 * *basis_two).abs()
                        < 1e-12
                );
            }
        }
    }
